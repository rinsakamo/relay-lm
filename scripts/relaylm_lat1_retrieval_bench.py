#!/usr/bin/env python3
"""LAT-1 offline retrieval scaling bench.

Calls the real M2 retrieval path (``build_relaymem_retrieval_dry_run_artifact``,
the same function ``app.py`` calls for the ``relaymem_retrieval`` RelayRUN
node) against synthetic stores generated by
``scripts/relaylm_lat1_bench_store_generator.py``, using a fixed synthetic
query set, and reports p50/p95 latency per store size.

This tool performs retrieval (search-stage) calls only -- no backend/LLM
call, no network access, no daemon. It is measurement-only and never
touches a production store root or a configured character store. See
``docs/architecture/lat1_latency_measurement.md`` for the reproduction
runbook.
"""

from __future__ import annotations

import argparse
import json
import random
import sys
import time
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))
if str(REPO_ROOT / "scripts") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "scripts"))

from relaylm.relaymem_retrieval import build_relaymem_retrieval_dry_run_artifact
from relaylm.relaymem_store import build_relaymem_store_diagnostics

from relaylm_lat1_bench_store_generator import (  # noqa: E402
    ALLOWED_ROOT,
    _SYNTHETIC_WORDS,
)

DEFAULT_STORES_ROOT = ALLOWED_ROOT / "stores"
DEFAULT_OUT_ROOT = ALLOWED_ROOT / "results"
DEFAULT_REPEAT = 5
DEFAULT_MAX_CANDIDATES = 3
QUERY_COUNT = 20
QUERY_SEED = 20260707

_SCENE_ARTIFACT: dict[str, Any] = {
    "scene_state": {"scene_type": "design_talk", "confidence": 0.95, "stability": 0.9},
    "scene_policy": {"relaymem_retrieval_scope": "project_context"},
    "persistence_block": False,
    "persistence_block_reasons": [],
}


def _build_query_set() -> list[str]:
    rng = random.Random(QUERY_SEED)
    return [" ".join(rng.sample(_SYNTHETIC_WORDS, k=3)) for _ in range(QUERY_COUNT)]


def _percentile(sorted_values: list[float], pct: float) -> float:
    if not sorted_values:
        return 0.0
    rank = max(0, min(len(sorted_values) - 1, int(round(pct / 100 * len(sorted_values))) - 1))
    return sorted_values[rank]


def _validate_bench_root(path: Path, *, flag_name: str) -> Path:
    resolved = path.resolve()
    try:
        resolved.relative_to(ALLOWED_ROOT)
    except ValueError:
        raise SystemExit(
            f"error: {flag_name} must resolve under {ALLOWED_ROOT} "
            f"(got {resolved}); refusing to read or write outside the gitignored "
            "LAT-1 bench directory"
        )
    return resolved


def _validate_store_dir(store_root: Path) -> Path:
    if store_root.is_symlink():
        raise SystemExit(
            "error: refusing to read symlinked bench store directory "
            f"(fail-closed): {store_root}"
        )
    resolved = store_root.resolve()
    try:
        resolved.relative_to(ALLOWED_ROOT)
    except ValueError:
        raise SystemExit(
            f"error: bench store directory must resolve under {ALLOWED_ROOT} "
            f"(got {resolved}); refusing to read outside the gitignored "
            "LAT-1 bench directory"
        )
    if not store_root.is_dir():
        raise SystemExit(f"error: expected store directory missing: {store_root}")
    return resolved


def _discover_sizes(stores_root: Path) -> list[int]:
    sizes = []
    for path in sorted(stores_root.glob("size_*")):
        if path.is_symlink() or not path.is_dir():
            continue
        try:
            sizes.append(int(path.name.removeprefix("size_")))
        except ValueError:
            continue
    return sizes


def _run_one_size(
    store_root: Path,
    *,
    size: int,
    queries: list[str],
    repeat: int,
    max_candidates: int,
) -> dict[str, Any]:
    latencies_ms: list[float] = []
    selected_counts: list[int] = []
    for _ in range(repeat):
        for query in queries:
            started = time.monotonic()
            store_diagnostics = build_relaymem_store_diagnostics(
                root_path=str(store_root),
                store_enabled=True,
                retrieval_dry_run_only=True,
            )
            artifact = build_relaymem_retrieval_dry_run_artifact(
                relayscn_scene_policy_artifact=_SCENE_ARTIFACT,
                messages=[{"role": "user", "content": query}],
                store_diagnostics=store_diagnostics,
                max_candidates=max_candidates,
            )
            latencies_ms.append((time.monotonic() - started) * 1000)
            selected = artifact.get("selected_mem_candidates")
            selected_counts.append(len(selected) if isinstance(selected, list) else 0)

    sorted_latencies = sorted(latencies_ms)
    avg_selected_count = (
        sum(selected_counts) / len(selected_counts) if selected_counts else 0.0
    )
    return {
        "store_size": size,
        "query_count": len(queries),
        "repeat": repeat,
        "p50_ms": round(_percentile(sorted_latencies, 50), 3),
        "p95_ms": round(_percentile(sorted_latencies, 95), 3),
        "avg_selected_count": round(avg_selected_count, 3),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stores-root", default=str(DEFAULT_STORES_ROOT))
    parser.add_argument("--out-root", default=str(DEFAULT_OUT_ROOT))
    parser.add_argument("--repeat", type=int, default=DEFAULT_REPEAT)
    parser.add_argument("--max-candidates", type=int, default=DEFAULT_MAX_CANDIDATES)
    parser.add_argument(
        "--sizes",
        default=None,
        help="Comma-separated sizes to bench; defaults to every size_<N> dir found under --stores-root.",
    )
    args = parser.parse_args()

    stores_root = _validate_bench_root(Path(args.stores_root), flag_name="--stores-root")
    out_root = _validate_bench_root(Path(args.out_root), flag_name="--out-root")

    if args.sizes:
        sizes = [int(token) for token in args.sizes.split(",") if token.strip()]
    else:
        sizes = _discover_sizes(stores_root)
    if not sizes:
        raise SystemExit(
            f"error: no size_<N> store directories found under {stores_root}; "
            "run scripts/relaylm_lat1_bench_store_generator.py first"
        )

    queries = _build_query_set()
    results = []
    for size in sizes:
        store_root = _validate_store_dir(stores_root / f"size_{size}")
        result = _run_one_size(
            store_root,
            size=size,
            queries=queries,
            repeat=args.repeat,
            max_candidates=args.max_candidates,
        )
        results.append(result)
        print(
            f"size={result['store_size']:>6} "
            f"p50_ms={result['p50_ms']:>8} "
            f"p95_ms={result['p95_ms']:>8} "
            f"avg_selected_count={result['avg_selected_count']:>6}"
        )

    out_root.mkdir(parents=True, exist_ok=True)
    out_path = out_root / "lat1_retrieval_bench_results.json"
    out_path.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())